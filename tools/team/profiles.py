"""One page per leader and growth partner (team-<slug>.html), from tools/team/main.html's profile templates
plus tools/team/profiles.json. Called by tools/team/build.py and tools/seo/seo.py."""
import json
import re
from html import escape, unescape
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
GROUPS = {"leadership": "Leadership", "partners": "Strategic Growth Partner"}
EXT = '<svg viewBox="0 0 16 16" width="12" height="12" aria-hidden="true"><path d="M6 3.5h6.5V10M12.5 3.5 4 12" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg>'


def page_of(slug):
    return f"team-{slug}.html"


def people():
    src = (HERE / "main.html").read_text(encoding="utf-8")
    tpl = {m[0]: m for m in re.findall(r'<template id="team-([\w-]+)" data-group="([^"]*)" data-title="([^"]*)"[^>]*>([\s\S]*?)</template>', src)}
    out = []
    for p in json.loads((HERE / "profiles.json").read_text(encoding="utf-8"))["people"]:
        _, role, title, body = tpl[p["slug"]]
        title, role = unescape(title), unescape(role)
        prefix = next((x for x in ("CA", "Adv.") if title.startswith(x + " ")), None)
        link = re.search(r'class="profile__linkedin"[^>]*?href="([^"]+)"', body)
        works = re.search(r'<details class="profile__works">[\s\S]*?<summary[^>]*>([^<]+)[\s\S]*?(<ul class="works"[\s\S]*?</ul>)', body)
        out.append({
            **p, "page": page_of(p["slug"]), "title": title, "name": title[len(prefix) + 1:] if prefix else title, "prefix": prefix, "role": role,
            "bio": unescape(re.sub(r"<[^>]+>", "", re.search(r'profile__bio">([\s\S]*?)</p>', body).group(1))),
            "linkedin": link.group(1) if link else None,
            "affiliations": [(unescape(alt), src_) for src_, alt in re.findall(r'<img [^>]*?src="(assets/logos/team/[^"]+)" alt="([^"]+)"', body)],
            "works_title": works.group(1).strip() if works else None, "works_html": works.group(2) if works else "",
            "books": [unescape(b) for b in re.findall(r'class="work">[\s\S]*?work__title">([^<]+)</p>', body)],
        })
    return out


def _press(ids):
    items = {i["id"]: i for i in json.loads((ROOT / "tools/press/press.json").read_text(encoding="utf-8"))["items"] if i["verificationStatus"] == "verified"}
    return "".join(f'''
            <li><a class="pv-row" href="{escape(items[i]["url"])}" target="_blank" rel="noopener noreferrer">
              <span class="pv-row__label">{escape(items[i]["publication"])}</span>
              <span class="pv-row__text"><span class="pv-row__title">{escape(items[i]["title"])}</span><span class="pv-row__sum">{escape(items[i]["typeLabel"])}</span></span>
              <span class="pv-row__meta">{escape(items[i]["dateLabel"])} {EXT}</span><span class="visually-hidden"> (opens in a new tab)</span>
            </a></li>''' for i in ids)


def pages():
    ps = people()
    out = []
    for p in ps:
        same = [q for q in ps if q["group"] == p["group"]]
        nxt = same[(same.index(p) + 1) % len(same)]
        back = "leadership" if p["group"] == "leadership" else "growth-partners"
        paras = "\n".join(f"          <p>{escape(x, quote=False)}</p>" for x in [p["bio"]] + p.get("more", []))
        li = (f'<a class="profile__linkedin" href="{escape(p["linkedin"])}" target="_blank" rel="noopener"><img class="profile__li" src="assets/brand/linkedin.webp" alt="" width="18" height="18" />LinkedIn profile<span class="visually-hidden"> (opens in a new tab)</span></a>'
              if p["linkedin"] else "")
        facts = "".join(f'\n          <section><h2 class="co-label">{escape(f["title"])}</h2><ul role="list">{"".join(f"<li>{escape(i, quote=False)}</li>" for i in f["items"])}</ul></section>' for f in p.get("facts", []))
        sections = ""
        if p["affiliations"]:
            lis = "".join(f'\n            <li><span class="pr-aff__logo"><img src="{s}" alt="" loading="lazy" decoding="async" /></span><span>{escape(a)}</span></li>' for a, s in p["affiliations"])
            sections += f'''
      <section class="pr-section" aria-labelledby="pr-aff"><h2 class="pr-h" id="pr-aff">Affiliations</h2>
          <ul class="pr-aff" role="list">{lis}
          </ul></section>'''
        if p["works_html"]:
            label = "Books" if p["books"] else p["works_title"]
            sections += f'\n      <section class="pr-section" aria-labelledby="pr-works"><h2 class="pr-h" id="pr-works">{escape(label)}</h2>\n          {p["works_html"]}</section>'
        if p.get("press"):
            sections += f'\n      <section class="pr-section" aria-labelledby="pr-press"><h2 class="pr-h" id="pr-press">In the press</h2>\n          <ul class="pv-rows" role="list">{_press(p["press"])}\n          </ul></section>'
        out.append((p["page"], f'''  <main id="main" class="pr-page">
    <!-- Generated by tools/team/profiles.py from tools/team/main.html and tools/team/profiles.json -->
    <article class="container pr-wrap" aria-labelledby="pr-name">
      <a class="co-back" href="team.html#{back}"><svg viewBox="0 0 16 16" width="14" height="14" aria-hidden="true"><path d="M10 3.5 5.5 8l4.5 4.5" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>Our team</a>
      <div class="pr-top">
        <aside class="pr-side" data-reveal>
          <img class="pr-photo" src="assets/team/{p["slug"]}.webp" alt="Portrait of {escape(p["name"])}" width="600" height="600" decoding="async" />{facts}
        </aside>
        <div class="pr-main" data-reveal style="--i:1">
          <p class="pr-group">{GROUPS[p["group"]]}</p>
          <h1 class="pr-name" id="pr-name">{escape(p["title"])}</h1>
          <p class="pr-role">{escape(p["role"])}</p>
          <div class="pr-bio">
{paras}
          </div>
          {li}
        </div>
      </div>{sections}
      <nav class="co-next" aria-label="Next profile">
        <a href="{nxt["page"]}"><span>Next profile</span><strong>{escape(nxt["title"])}</strong><svg viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path d="M3 8h9.5M8.5 4l4 4-4 4" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg></a>
      </nav>
    </article>
  </main>''', p["bio"]))
    return out
